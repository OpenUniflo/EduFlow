#!/usr/bin/env node
/**
 * Generates the root `requirements.txt` for the merged Vercel Python Function from
 * `services/workflow/uv.lock`. The lock file remains authoritative; this file only exists
 * because the Vercel Python runtime installs dependencies from `requirements.txt`.
 *
 * Usage:
 *   node scripts/workflow/export-requirements.mjs           # regenerate
 *   node scripts/workflow/export-requirements.mjs --check   # fail on drift (CI gate)
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const output = fileURLToPath(new URL("../../requirements.txt", import.meta.url));
const commands = ["uv", "export", "--project", "services/workflow", "--no-dev", "--frozen", "--no-hashes", "--no-emit-project"];
const header = [
  "# Generated by scripts/workflow/export-requirements.mjs from services/workflow/uv.lock.",
  "# Do not edit by hand. Regenerate with: node scripts/workflow/export-requirements.mjs",
  "",
].join("\n");

const check = process.argv.length === 3 && process.argv[2] === "--check";
if (process.argv.length > 3 || (process.argv.length === 3 && !check)) throw new Error("This script accepts only the optional --check flag.");

const exported = spawnSync(commands[0], commands.slice(1), { cwd: root, encoding: "utf8" });
if (exported.error) throw exported.error;
if (exported.status !== 0) {
  process.stderr.write(exported.stderr ?? "");
  process.exit(exported.status ?? 1);
}
const generated = header + exported.stdout.replace(/\r\n/g, "\n");
if (check) {
  let existing;
  try {
    existing = readFileSync(output, "utf8").replace(/\r\n/g, "\n");
  } catch {
    existing = undefined;
  }
  if (existing !== generated) {
    console.error("requirements.txt is out of date with services/workflow/uv.lock; run `node scripts/workflow/export-requirements.mjs`.");
    process.exit(1);
  }
  console.log("PASS: requirements.txt matches services/workflow/uv.lock");
} else {
  writeFileSync(output, generated);
  console.log("Wrote requirements.txt from services/workflow/uv.lock");
}
