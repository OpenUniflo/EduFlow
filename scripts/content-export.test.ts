import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it, vi } from "vitest";
import {
  CONTENT_TABLES,
  buildContentSnapshot,
  formatExportSummary,
  renderContentSnapshot,
  replayContentSnapshotInRollback,
  sqlLiteral,
  writeContentSnapshot,
  type ContentTableData
} from "./content-export";
import { CONTENT_SNAPSHOT_HEADER } from "./content-import";
import { LOCAL_ONLY_SUPABASE_ERROR } from "./local-supabase";

const generatedAt = "2026-11-01T00:00:00.000Z";

function table(overrides: Partial<ContentTableData> = {}): ContentTableData {
  return {
    table: "sample_rows",
    columns: [
      { name: "id", type: "text" },
      { name: "count", type: "integer" },
      { name: "enabled", type: "boolean" },
      { name: "payload", type: "jsonb" }
    ],
    primaryKey: ["id"],
    rows: [
      { id: "b", count: "2", enabled: "false", payload: '{"z":1}' },
      { id: "a", count: "1", enabled: "true", payload: null }
    ],
    ...overrides
  };
}

describe("content export rendering", () => {
  it("renders an import-compatible snapshot with deterministic upserts", () => {
    const sql = renderContentSnapshot([table()], generatedAt);
    expect(sql.startsWith(CONTENT_SNAPSHOT_HEADER)).toBe(true);
    expect(sql).toContain("begin;\nset constraints all deferred;");
    expect(sql.trimEnd().endsWith("commit;")).toBe(true);
    expect(sql).toContain(`insert into public.sample_rows (id, count, enabled, payload) values ('b', 2, false, '{"z":1}') on conflict (id) do update set count = excluded.count, enabled = excluded.enabled, payload = excluded.payload;`);
    expect(sql).toContain(`insert into public.sample_rows (id, count, enabled, payload) values ('a', 1, true, NULL) on conflict (id) do update set count = excluded.count, enabled = excluded.enabled, payload = excluded.payload;`);
    expect(sql.indexOf("values ('a'")).toBeLessThan(sql.indexOf("values ('b'"));
  });

  it("exports the Workflow template purpose discriminator", () => {
    const sql = renderContentSnapshot([{
      table: "workflow_templates",
      columns: [{ name: "id", type: "text" }, { name: "definition", type: "jsonb" }, { name: "purpose", type: "text" }],
      primaryKey: ["id"],
      rows: [{ id: "starter-assistant", definition: '{"schemaVersion":"2.0"}', purpose: "starter" }]
    }], generatedAt);
    expect(sql).toContain(`insert into public.workflow_templates (id, definition, purpose) values ('starter-assistant', '{"schemaVersion":"2.0"}', 'starter') on conflict (id) do update set definition = excluded.definition, purpose = excluded.purpose;`);
  });

  it("uses do nothing when every exported column is part of the primary key", () => {
    const sql = renderContentSnapshot([table({
      table: "join_rows",
      columns: [{ name: "left_id", type: "text" }, { name: "right_id", type: "text" }],
      primaryKey: ["left_id", "right_id"],
      rows: [{ left_id: "a", right_id: "b" }]
    })], generatedAt);
    expect(sql).toContain(`on conflict (left_id, right_id) do nothing;`);
  });

  it("escapes quotes, backslashes, newlines and control characters into E-strings", () => {
    expect(sqlLiteral("plain", "text")).toBe("'plain'");
    expect(sqlLiteral("it's", "text")).toBe("'it''s'");
    expect(sqlLiteral("line one\nline two", "text")).toBe("E'line one\\nline two'");
    expect(sqlLiteral("back\\slash", "text")).toBe("E'back\\\\slash'");
    expect(sqlLiteral("\u0001", "text")).toBe("E'\\x01'");
    expect(sqlLiteral(null, "text")).toBe("NULL");
    expect(sqlLiteral("42", "integer")).toBe("42");
    expect(sqlLiteral("true", "boolean")).toBe("true");
    expect(() => sqlLiteral("not-a-number", "integer")).toThrow(/non-numeric/);
  });

  it("changes only the timestamp between two exports of the same rows", () => {
    const first = renderContentSnapshot([table()], "2026-11-01T00:00:00.000Z");
    const second = renderContentSnapshot([table()], "2026-11-01T00:00:01.000Z");
    const withoutTimestamp = (value: string) => value.replace(/^-- Generated by.*$/m, "-- Generated");
    expect(withoutTimestamp(first)).toBe(withoutTimestamp(second));
  });

  it("writes the snapshot under content-snapshots with a UTC timestamp name", () => {
    const directory = mkdtempSync(join(tmpdir(), "eduflow-content-export-"));
    const snapshot = {
      generatedAt,
      sql: renderContentSnapshot([table()], generatedAt),
      tables: [table()],
      storageObjects: []
    };
    const path = writeContentSnapshot(snapshot, directory);
    expect(path.endsWith("eduflow-content-20261101T000000Z.sql")).toBe(true);
    expect(readFileSync(path, "utf8")).toBe(snapshot.sql);
  });
});

describe("content export scope and safety", () => {
  it("lists product tables and excludes user, learner, route, run and session tables", () => {
    const tables = new Set(CONTENT_TABLES.map((spec) => spec.table));
    for (const included of ["courses", "knowledge_nodes", "knowledge_edges", "materials", "micro_steps", "workflow_templates", "mastery_criteria"]) {
      expect(tables.has(included)).toBe(true);
    }
    for (const excluded of ["profiles", "user_knowledge_states", "personal_course_routes", "learning_attempts", "workflow_live_runs", "assistant_sessions", "knowledge_evidence"]) {
      expect(tables.has(excluded)).toBe(false);
    }
    const courses = CONTENT_TABLES.find((spec) => spec.table === "courses");
    expect(courses?.excludedColumns).toEqual(expect.arrayContaining(["author_user_id", "owner_user_id", "creation_brief_message_id"]));
    expect(CONTENT_TABLES.find((spec) => spec.table === "knowledge_domains")?.redactedColumns).toEqual({ created_by: "global-admin-demo", updated_by: "global-admin-demo" });
    expect(CONTENT_TABLES.find((spec) => spec.table === "knowledge_node_revisions")?.excludedColumns).toContain("created_by");
    expect(CONTENT_TABLES.find((spec) => spec.table === "domain_assignments")?.excludedColumns).toContain("assigned_by");
  });

  it("rejects a non-Local Supabase URL before querying the database", () => {
    const query = vi.fn();
    expect(() => buildContentSnapshot({ supabaseUrl: "https://example.supabase.co", query })).toThrow(LOCAL_ONLY_SUPABASE_ERROR);
    expect(query).not.toHaveBeenCalled();
  });

  it("summarizes rows and referenced storage objects without exporting binaries", () => {
    const summary = formatExportSummary({
      generatedAt,
      sql: "",
      tables: [table({ rows: [table().rows[0]] })],
      storageObjects: [{ bucket: "course-materials", path: "shared/course/lesson.pdf" }, { bucket: "micro-h5p", path: "h5p/1" }]
    }, "content-snapshots/eduflow-content-20261101T000000Z.sql");
    expect(summary).toContain("| public.sample_rows | 1 |");
    expect(summary).toContain("- course-materials/shared/course/lesson.pdf");
    expect(summary).toContain("- micro-h5p/h5p/1");
  });

  it("replays into the same transaction and rolls back instead of committing", () => {
    const sql = renderContentSnapshot([table()], generatedAt);
    const run = vi.fn((_sql: string) => "content snapshot replay ok");
    replayContentSnapshotInRollback(sql, { supabaseUrl: "http://127.0.0.1:54321", run });
    expect(run).toHaveBeenCalledOnce();
    const replay = run.mock.calls[0]?.[0] ?? "";
    expect(replay).not.toMatch(/\ncommit;\s*$/);
    expect(replay).toContain("select 'content snapshot replay ok' as replay;");
    expect(replay.trimEnd().endsWith("rollback;")).toBe(true);
  });

  it("refuses to replay an unrecognized or non-Local snapshot", () => {
    const run = vi.fn();
    expect(() => replayContentSnapshotInRollback("select 1;", { supabaseUrl: "http://127.0.0.1:54321", run })).toThrow(/unrecognized/);
    expect(() => replayContentSnapshotInRollback(renderContentSnapshot([table()], generatedAt), { supabaseUrl: "https://example.supabase.co", run })).toThrow(LOCAL_ONLY_SUPABASE_ERROR);
    expect(run).not.toHaveBeenCalled();
  });
});
